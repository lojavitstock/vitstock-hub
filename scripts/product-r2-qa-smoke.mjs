const localR2Values = new Map();
for (const line of readFileSync(r2EnvPath, 'utf8').split(/\r?\n/)) {
  const match = line.match(/^\s*(R2_ACCESS_KEY_ID|R2_SECRET_ACCESS_KEY)\s*=\s*(.*?)\s*$/);
  if (!match) continue;
  localR2Values.set(match[1], match[2].replace(/^['"]|['"]$/g, ''));
}
for (const key of ['R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY']) {
  if (!process.env[key] && localR2Values.get(key)) process.env[key] = localR2Values.get(key);
}


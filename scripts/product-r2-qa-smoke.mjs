const objectKeys = new Set();

async function api(path, init = {}) {
  const headers = new Headers(init.headers || {});
  if (cookie) headers.set('cookie', cookie);
  if (init.body !== undefined) headers.set('content-type', 'application/json');
  const response = await fetch(`${apiBase}${path}`, {
    ...init,
    headers,
    body: init.body === undefined ? undefined : JSON.stringify(init.body),
  });
  let data;
  try { data = await response.json(); } catch { data = null; }
  return { response, data };
}

function keyFromImageUrl(imageUrl, productIdForUrl) {
  const url = new URL(imageUrl);
  const base = new URL(process.env.R2_PUBLIC_BASE_URL);
  assert.equal(url.origin, base.origin);
  const key = decodeURIComponent(url.pathname.replace(/^\//, ''));
  assert.ok(key.startsWith(`products/${companyId}/${productIdForUrl}/`));
  assert.match(key, /\.(?:jpg|png|webp)$/);
  objectKeys.add(key);
  return key;
}

async function assertPublicImage(imageUrl) {
  const response = await fetch(imageUrl, { cache: 'no-store' });
  assert.equal(response.status, 200);
  assert.match(response.headers.get('content-type') || '', /^image\/(?:jpeg|png|webp)/);
  assert.ok((await response.arrayBuffer()).byteLength > 0);
}

async function loadInBrowser(imageUrl) {
  const imageBrowser = await chromium.launch({ headless: true });
  try {
    const page = await imageBrowser.newPage();
    await page.setContent(`<img id="product-image" src="${imageUrl.replaceAll('&', '&amp;').replaceAll('"', '&quot;')}" />`);
    await page.waitForFunction(() => {
      const image = document.querySelector('#product-image');
      return image instanceof HTMLImageElement && image.complete && image.naturalWidth > 0;
    }, undefined, { timeout: 20_000 });
  } finally {
    await imageBrowser.close().catch(() => undefined);
  }
}

